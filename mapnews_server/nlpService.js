/**
 * Classify category based on title & text patterns
 */
function classifyCategory(title = '', text = '') {
    // 1. Check title first (highest accuracy)
    for (const cat of CATEGORY_RULES) {
        if (cat.titleRegex && cat.titleRegex.test(title)) {
            return cat.name;
        }
    }

    // 2. Fallback to text
    if (text) {
        for (const cat of CATEGORY_RULES) {
            if (cat.titleRegex && cat.titleRegex.test(text)) {
                return cat.name;
            }
        }
    }

    return 'Общество';
}

// Lazy-loaded Neural Model
let sentimentPipeline = null;
let pipelineInitializing = false;

async function getSentimentPipeline() {
    if (sentimentPipeline) return sentimentPipeline;
    if (pipelineInitializing) return null;

    pipelineInitializing = true;
    try {
        const { pipeline } = await import('@xenova/transformers');
        sentimentPipeline = await pipeline('sentiment-analysis', 'Xenova/bert-base-multilingual-uncased-sentiment', {
            quantized: true
        });
        console.log('✓ [NLP] Нейросетевая модель тональности успешно загружена');
    } catch (err) {
        console.warn('! [NLP] Локальная нейросеть недоступна, работает быстрый эвристический классификатор');
    } finally {
        pipelineInitializing = false;
    }
    return sentimentPipeline;
}

