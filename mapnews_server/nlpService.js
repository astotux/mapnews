/**
 * Detect Komi District based on geographical keywords & settlement names
 */
function detectDistrict(title = '', text = '') {
    const fullText = `${title} ${text}`;
    for (const district of KOMI_DISTRICTS) {
        for (const pattern of district.patterns) {
            if (pattern.test(fullText)) {
                return district.name;
            }
        }
    }
    return null;
}

/**
 * Resolve District with headline priority over site category page
 */
function resolveDistrict(title = '', text = '', currentPlace = null) {
    // 1. Look in title specifically first (headlines are most accurate)
    for (const district of KOMI_DISTRICTS) {
        for (const pattern of district.patterns) {
            if (pattern.test(title)) {
                return district.name;
            }
        }
    }

    // 2. Check if title is explicitly Regional (all-Komi scope)
    if (REGIONAL_TITLE_PATTERN.test(title)) {
        return null;
    }

    // 3. Fallback to currentPlace if available and not general
    if (currentPlace && currentPlace !== 'Не указано') {
        return currentPlace;
    }

    // 4. Look in text body
    if (text) {
        for (const district of KOMI_DISTRICTS) {
            for (const pattern of district.patterns) {
                if (pattern.test(text)) {
                    return district.name;
                }
            }
        }
    }

    return null;
}

